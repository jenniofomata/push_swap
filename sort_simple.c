#include "push_swap.h"

void	sort_simple(t_ps *ps)
{
	while (ps->a.size > 0)
	{
		rot_a_to(ps, min_index(&ps->a));
		op_pb(ps);
	}
	while (ps->b.size > 0)
	{
		op_pa(ps);
	}
}
