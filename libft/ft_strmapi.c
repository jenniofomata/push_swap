#include "libft.h"

char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	unsigned int	i;
	char			*result;
	size_t			s_len;

	if (!s || !f)
		return (NULL);
	s_len = 0;
	while (s[s_len])
	{
		s_len++;
	}
	result = (char *)malloc(s_len + 1);
	if (!result)
		return (NULL);
	i = 0;
	while (i < s_len)
	{
		result[i] = f(i, s[i]);
		i++;
	}
	result[i] = '\0';
	return (result);
}
